const DICTS: Record<Lang, Dict> = { en, hi, gu };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let out: string = DICTS[lang][key];
  if (vars) for (const k in vars) out = out.replaceAll(`{${k}}`, String(vars[k]));
  return out;
}

// ---- Times and dates -------------------------------------------------------

const PERIODS: Record<"hi" | "gu", [number, string][]> = {
  hi: [[240, "रात"], [720, "सुबह"], [960, "दोपहर"], [1200, "शाम"], [1440, "रात"]],
  gu: [[240, "રાત્રે"], [720, "સવારે"], [960, "બપોરે"], [1200, "સાંજે"], [1440, "રાત્રે"]],
};

function clock(min: number): string {
  const h = Math.floor(min / 60), m = min % 60;
  return `${h % 12 === 0 ? 12 : h % 12}:${String(m).padStart(2, "0")}`;
}

function period(min: number, lang: "hi" | "gu"): string {
  return PERIODS[lang].find(([end]) => min < end)![1];
}

/** "5:30 PM" / "शाम 5:30" / "સાંજે 5:30". */
export function fmtTime(min: number, lang: Lang = "en"): string {
  if (lang === "en") return `${clock(min)} ${min < 720 ? "AM" : "PM"}`;
  return `${period(min, lang)} ${clock(min)}`;
}

/** As it reads inside a sentence: "5:30 PM" / "शाम 5:30 बजे" / "સાંજે 5:30 વાગ્યે". */
export function fmtTimeAt(min: number, lang: Lang): string {
  if (lang === "hi") return `${fmtTime(min, lang)} बजे`;
  if (lang === "gu") return `${fmtTime(min, lang)} વાગ્યે`;
  return fmtTime(min, lang);
}

/** "till 9:00 PM" / "रात 9:00 बजे तक" / "રાત્રે 9:00 વાગ્યા સુધી". */
export function fmtUntil(min: number, lang: Lang): string {
  if (lang === "hi") return `${fmtTime(min, lang)} बजे तक`;
  if (lang === "gu") return `${fmtTime(min, lang)} વાગ્યા સુધી`;
  return `till ${fmtTime(min, lang)}`;
}

const LOCALE: Record<Lang, string> = { en: "en-IN", hi: "hi-IN", gu: "gu-IN" };

function intl(date: DateStr, lang: Lang, opts: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(LOCALE[lang], { ...opts, timeZone: "UTC", numberingSystem: "latn" }).format(
    new Date(date + "T00:00:00Z"),
  );
}

export function fmtWeekday(date: DateStr, lang: Lang, width: "short" | "long" = "short"): string {
  return intl(date, lang, { weekday: width });
}

/** "Thu, 8 Oct". */
export function fmtDate(date: DateStr, lang: Lang): string {
  return intl(date, lang, { weekday: "short", day: "numeric", month: "short" });
}

/** English, for the middle of a desk sentence: "today" / "tomorrow" / "Thu, 8 Oct". */
export function fmtDayInline(date: DateStr, today: DateStr): string {
  return fmtDay(date, "en", today).replace(/^T(?=oday|omorrow)/, "t");
}

/** "Today" / "Tomorrow" / "Thu, 8 Oct". */
export function fmtDay(date: DateStr, lang: Lang, today: DateStr): string {
  if (date === today) return translate(lang, "today");
  if (date === addDays(today, 1)) return translate(lang, "tomorrow");
  return fmtDate(date, lang);
}
